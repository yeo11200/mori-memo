import { _electron as electron, expect } from '@playwright/test';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const directory = await mkdtemp(join(tmpdir(), 'mori-050-'));
const packaged = process.argv.includes('--packaged');
const app = await electron.launch({ ...(packaged ? { executablePath: resolve('release/mac-arm64/MORI.app/Contents/MacOS/MORI'), args: [] } : { args: [resolve('.')] }), env: { ...process.env, WIKI_DATA_DIR: directory } });
try {
  const page = await app.firstWindow();
  await page.waitForFunction(() => Boolean(window.wiki));
  const sourceId = await page.evaluate(async () => {
    const target = await window.wiki.handleCreateNote('blank');
    await window.wiki.handleSaveNote({ ...target, title: '배포 체크리스트', body: '배포 준비와 검증' });
    const source = await window.wiki.handleCreateNote('blank');
    await window.wiki.handleSaveNote({ ...source, title: '배포 계획', body: '배포 준비를 시작합니다.' });
    return source.id;
  });
  await page.reload();
  await page.getByTitle('설정', { exact: true }).click();
  await page.getByLabel('AI 연결 방식').selectOption('codex');
  const models = page.getByLabel('모델', { exact: true });
  await expect(models.locator('option[value="gpt-5.6-sol"]')).toHaveCount(1);
  await models.selectOption('gpt-5.6-sol');
  await page.getByRole('button', { name: '모델 목록 새로고침' }).click();
  await expect(page.getByRole('button', { name: '모델 목록 새로고침' })).toBeEnabled();
  await expect(models).toHaveValue('gpt-5.6-sol');
  await page.getByLabel('AI 연결 방식').selectOption('claude');
  await expect(models.locator('option[value="sonnet"]')).toHaveCount(1);
  await expect(models.locator('option[value="opus"]')).toHaveCount(1);
  await expect(models.locator('option[value="fable"]')).toHaveCount(1);
  await models.selectOption('sonnet');
  await page.getByRole('button', { name: '설정 저장', exact: true }).click();
  await page.getByTitle('설정', { exact: true }).click();
  await expect(models).toHaveValue('sonnet');
  await page.getByRole('button', { name: '설정 닫기' }).click();
  await page.getByRole('button', { name: '사용 가이드', exact: true }).click();
  const guide = page.getByRole('dialog', { name: 'MORI 사용 가이드' });
  await expect(guide).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(guide).not.toBeVisible();
  await page.locator('.wiki__note-row').filter({ hasText: '배포 계획' }).click();
  await expect(page.locator('.wiki__links-panel .wiki__ai-card')).toHaveCount(0);
  const connect = page.getByRole('button', { name: '배포 체크리스트 연결', exact: true });
  await connect.click();
  const dialog = page.getByRole('dialog', { name: '메모 연결' });
  await expect(dialog.getByRole('button', { name: '연결 추가', exact: true })).toBeEnabled();
  await dialog.getByLabel('연결 이유', { exact: true }).fill('배포 전에 검증할 항목');
  await dialog.getByRole('button', { name: '연결 추가', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(connect).toHaveCount(0);
  await page.reload();
  const note = await page.evaluate(async id => (await window.wiki.handleBootstrap()).notes.find(note => note.id === id), sourceId);
  expect(note.body).toContain('배포 준비를 시작합니다.');
  expect(note.body).toContain('배포 전에 검증할 항목');
  expect(note.body).toContain('[[');
  await page.screenshot({ path: join(directory, 'release.png') });
  console.log('PASS: guide, recommendation preselection, link persistence, original body preservation; ' + directory);
} finally { await app.close(); }
